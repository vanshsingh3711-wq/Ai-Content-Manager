export function isPresetOrLocalId(id: string | null | undefined): boolean {
  if (!id) return false;
  return (
    id === "demo" ||
    id === "new" ||
    id.startsWith("preset-") ||
    id.startsWith("template-") ||
    id.startsWith("local-")
  );
}

