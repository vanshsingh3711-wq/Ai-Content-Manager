/**
 * Returns all resources in the catalog.
 */
export function getAllResources(): LibraryResource[] {
  return RESOURCE_CATALOG;
}

/**
 * Retrieves a resource by its unique stable ID.
 */
export function getResourceById(id: string): LibraryResource | undefined {
  return RESOURCE_CATALOG.find((r) => r.id === id);
}

/**
 * Returns all resources belonging to a specific resource type.
 */
export function getResourcesByType(type: LibraryResourceType): LibraryResource[] {
  return RESOURCE_CATALOG.filter((r) => r.type === type);
}

/**
 * Searches and filters resources across name, category, description, and tags.
 */
export function searchResources(
  query: string = "",
  filters?: {
    type?: LibraryResourceType;
    category?: string;
    aspectRatio?: string;
    subCategory?: string;
    sortBy?: "default" | "name" | "duration_asc" | "duration_desc";
  }
): LibraryResource[] {
  const q = query.trim().toLowerCase();

  let list = RESOURCE_CATALOG.filter((res) => {
    if (filters?.type && res.type !== filters.type) return false;
    if (filters?.category && filters.category !== "All" && res.category !== filters.category) {
      return false;
    }
    if (filters?.aspectRatio && filters.aspectRatio !== "all") {
      if (res.aspectRatio !== filters.aspectRatio) {
        return false;
      }
    }
    if (filters?.subCategory && filters.subCategory !== "all") {
      if (!res.subCategory || res.subCategory.toLowerCase() !== filters.subCategory.toLowerCase()) {
        return false;
      }
    }

    if (!q) return true;

    const matchesName = res.name.toLowerCase().includes(q);
    const matchesCategory = res.category.toLowerCase().includes(q);
    const matchesSubCategory = (res.subCategory || "").toLowerCase().includes(q);
    const matchesDesc = res.description.toLowerCase().includes(q);
    const matchesTag = res.tags.some((t) => t.toLowerCase().includes(q));

    return matchesName || matchesCategory || matchesSubCategory || matchesDesc || matchesTag;
  });

  if (filters?.sortBy && filters.sortBy !== "default") {
    list = [...list].sort((a, b) => {
      if (filters.sortBy === "name") {
        return a.name.localeCompare(b.name);
      }
      if (filters.sortBy === "duration_asc") {
        return a.defaultDuration - b.defaultDuration;
      }
      if (filters.sortBy === "duration_desc") {
        return b.defaultDuration - a.defaultDuration;
      }
      return 0;
    });
  }

  return list;
}

/**
 * Validates a resource definition using Zod.
 */
export function validateResource(raw: unknown): LibraryResource {
  return LibraryResourceSchema.parse(raw);
}

/**
 * Factory that translates a chosen LibraryResource and user-configured options
 * into an exact, transactional EditOperation for the editor's operational bus.
 */
export function createOperationFromResource(
  resource: LibraryResource,
  options: ResourceApplyOptions
): ResourceApplyResult {
  if (!resource.isSupported) {
    return {
      success: false,
      error: `Resource '${resource.name}' is an expansion entry and not yet supported in this build.`,
    };
  }

  const timestamp = Math.max(0, options.timestamp);
  const duration = Math.max(0.1, options.duration || resource.defaultDuration);
  const end = Number((timestamp + duration).toFixed(3));
  const props = { ...resource.defaultProps, ...(options.customProps || {}) };
  const id = `${resource.id}-${Date.now()}`;

  switch (resource.type) {
    // 1. Shapes -> add_element on 'graphic' track with compositionId 'shape'
    case "shape": {
      const pos = options.position || { x: 50, y: 50 };
      const op: EditOperation = {
        type: "add_element",
        track: "graphic",
        element: {
          id,
          name: resource.name,
          compositionId: "shape",
          props,
          start: timestamp,
          end,
          position: pos,
          positionX: pos.x,
          positionY: pos.y,
          scale: 1.0,
          rotation: 0,
          opacity: props.opacity ?? 90,
        },
      };
      return { success: true, operation: op };
    }

    // 2. Caption Presets -> apply style effects to existing text instead of adding redundant caption blocks to timeline
    case "caption_preset": {
      const stylePreset =
        props.stylePreset ||
        (resource.id.startsWith("cap-")
          ? resource.id.replace("cap-", "").replace(/-/g, "_")
          : "tiktok_yellow");

      const styleProps: Record<string, any> = {
        stylePreset,
      };
      if (props.fontSize !== undefined) styleProps.fontSize = props.fontSize;
      if (props.textColor !== undefined) styleProps.textColor = props.textColor;
      if (props.highlightColor !== undefined) styleProps.highlightColor = props.highlightColor;
      if (props.position) styleProps.position = props.position;
      if (props.scale !== undefined) styleProps.scale = props.scale;

      // 1) Explicit target caption is selected/specified:
      if (options.targetCaptionId) {
        const op: EditOperation = {
          type: "update_properties",
          targetType: "caption",
          targetId: options.targetCaptionId,
          properties: styleProps,
        };
        return { success: true, operation: op };
      }

      // 2) Existing captions exist on the timeline -> apply effect directly to text!
      if (options.existingCaptions && options.existingCaptions.length > 0) {
        const operations: EditOperation[] = options.existingCaptions.map((cap: any) => ({
          type: "update_properties" as const,
          targetType: "caption" as const,
          targetId: cap.id,
          properties: { ...styleProps },
        }));

        if (operations.length === 1) {
          return { success: true, operation: operations[0] };
        }

        const batchOp: EditOperation = {
          type: "batch",
          description: `Apply '${resource.name}' caption effect to all text`,
          operations,
        };
        return { success: true, operation: batchOp };
      }

      // 3) Fallback: only if project has ZERO captions, create an initial caption element
      const pos = options.position || { x: 50, y: 75 };
      const text = options.text || props.text || resource.name;
      const op: EditOperation = {
        type: "add_element",
        track: "caption",
        element: {
          id,
          text,
          start: timestamp,
          end,
          stylePreset,
          fontSize: props.fontSize,
          textColor: props.textColor,
          highlightColor: props.highlightColor,
          position: pos,
          positionX: pos.x,
          positionY: pos.y,
          scale: 1.0,
          rotation: 0,
        },
      };
      return { success: true, operation: op };
    }

    // 3. Transitions -> add_transition between adjacent clips
    case "transition": {
      if (!options.targetClipAId || !options.targetClipBId) {
        return {
          success: false,
          error: "Applying a transition requires selecting two adjacent clips (outgoing and incoming).",
        };
      }
      const op: EditOperation = {
        type: "add_transition",
        id: `trans-${Date.now()}`,
        track: "video",
        fromClipId: options.targetClipAId,
        toClipId: options.targetClipBId,
        preset: (props.preset || "crossfade") as TransitionPreset,
        duration: duration,
        alignment: (props.alignment || "center") as "center" | "start" | "end",
        validateHandles: false,
        autoClamp: false,
        enforceFallback: false,
      };
      return { success: true, operation: op };
    }

    // 4. Motion Graphics -> add_element on 'graphic' track
    case "motion_graphic": {
      const pos = options.position || { x: 50, y: 50 };
      const compId = props.compositionId || "hero_reveal";
      const op: EditOperation = {
        type: "add_element",
        track: "graphic",
        element: {
          id,
          name: resource.name,
          compositionId: compId,
          props: { ...props, resourceId: resource.id },
          start: timestamp,
          end,
          position: pos,
          positionX: pos.x,
          positionY: pos.y,
          scale: 1.0,
          rotation: 0,
        },
      };
      return { success: true, operation: op };
    }

    // 5. Sound FX -> add_element on 'audio' track
    case "sfx": {
      const op: EditOperation = {
        type: "add_element",
        track: "audio",
        element: {
          id,
          name: resource.name,
          sourceUrl: props.sourceUrl || "/assets/audio/whoosh.mp3",
          start: timestamp,
          end,
          volume: props.volume ?? 80,
          fadeIn: 0.05,
          fadeOut: 0.05,
          isBgm: false,
        },
      };
      return { success: true, operation: op };
    }

    // 6. Stock B-Roll -> add_element on 'broll' track
    case "broll": {
      const pos = options.position || { x: 50, y: 50 };
      const op: EditOperation = {
        type: "add_element",
        track: "broll",
        element: {
          id,
          name: resource.name,
          sourceUrl: props.sourceUrl,
          start: timestamp,
          end,
          opacity: props.opacity ?? 100,
          fitMode: props.fitMode || "cover",
          volume: 0,
          muted: true,
          position: pos,
          positionX: pos.x,
          positionY: pos.y,
          scale: 1.0,
          rotation: 0,
        },
      };
      return { success: true, operation: op };
    }

    // 7. Visual Effects & Filters -> add_element on 'graphic' track as effect_overlay
    case "effect": {
      const pos = options.position || { x: 50, y: 50 };
      const op: EditOperation = {
        type: "add_element",
        track: "graphic",
        element: {
          id,
          name: resource.name,
          compositionId: "effect_overlay",
          props: {
            effectType: props.effectType || resource.id.replace("fx-", ""),
            intensity: props.intensity ?? 80,
            ...props,
          },
          start: timestamp,
          end,
          position: pos,
          positionX: pos.x,
          positionY: pos.y,
          scale: 1.0,
          rotation: 0,
          opacity: props.opacity ?? 90,
        },
      };
      return { success: true, operation: op };
    }

    default:
      return {
        success: false,
        error: `Unsupported resource type: ${(resource as any).type}`,
      };
  }
}
