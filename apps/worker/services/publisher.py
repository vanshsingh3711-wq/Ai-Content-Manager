def _wait_for_internet_retry(func):
    """Bounded retry decorator for storage upload operations (up to 5 attempts with backoff and jitter)."""
    return bounded_network_retry(
        max_retries=5,
        base_delay=1.0,
        max_delay=30.0,
        backoff_factor=2.0,
        jitter=True,
        retryable_exceptions=(
            requests.exceptions.ConnectionError,
            requests.exceptions.Timeout,
            socket.error,
            ConnectionError,
            TimeoutError,
        ),
    )(func)


def get_s3_client():
    """Returns configured boto3 S3 client if full credentials and bucket are configured."""
    if not (settings.R2_ACCESS_KEY_ID and settings.R2_SECRET_ACCESS_KEY and settings.R2_BUCKET_NAME):
        return None

    endpoint_url = settings.R2_ENDPOINT_URL
    if not endpoint_url and settings.R2_ACCOUNT_ID:
        endpoint_url = f"https://{settings.R2_ACCOUNT_ID}.r2.cloudflarestorage.com"

    return boto3.client(
        "s3",
        endpoint_url=endpoint_url,
        aws_access_key_id=settings.R2_ACCESS_KEY_ID,
        aws_secret_access_key=settings.R2_SECRET_ACCESS_KEY,
    )


@_wait_for_internet_retry
def upload_rendered_video_to_storage(
    local_mp4_path: str,
    job_id: str,
    user_id: str = "default_user",
) -> str:
    """
    Uploads the final rendered video to Cloudflare R2 / AWS S3 or persists locally for FastAPI dev streaming.
    """
    if not os.path.exists(local_mp4_path):
        raise FileNotFoundError(f"Rendered file not found: {local_mp4_path}")

    s3_client = get_s3_client()
    bucket_name = settings.R2_BUCKET_NAME or "ai-video-manager-uploads"
    file_key = f"rendered-exports/{user_id}/{job_id}_final.mp4"

    if s3_client:
        print(f"[*] Uploading rendered video to R2/S3: s3://{bucket_name}/{file_key}...")
        s3_client.upload_file(
            local_mp4_path,
            bucket_name,
            file_key,
            ExtraArgs={"ContentType": "video/mp4"},
        )

        if settings.R2_ENDPOINT_URL:
            public_url = f"{settings.R2_ENDPOINT_URL.rstrip('/')}/{bucket_name}/{file_key}"
        else:
            public_url = f"https://{bucket_name}.s3.amazonaws.com/{file_key}"
        print(f"[OK] Video uploaded successfully: {public_url}")
        return public_url

    # Local development storage: Persist copy to media_temp for streaming via localhost:8000
    persistent_local_dest = os.path.join(MEDIA_TEMP_DIR, file_key.replace("/", os.sep))
    os.makedirs(os.path.dirname(persistent_local_dest), exist_ok=True)
    shutil.copyfile(local_mp4_path, persistent_local_dest)
    print(f"[OK] Persisted rendered video for local streaming at: {persistent_local_dest}")

    return f"http://localhost:8000/api/v1/storage/download?key={file_key}"


@_wait_for_internet_retry
def publish_to_youtube(
    video_path: str,
    title: str,
    description: str = "",
    is_shorts: bool = False,
    access_token: Optional[str] = None,
) -> Dict[str, Any]:
    """
    Publishes the rendered video to YouTube via YouTube Data API v3.
    Supports both Shorts and Long-form videos.
    """
    video_format = "Shorts" if is_shorts else "Long-form"
    print(f"[*] Publishing to YouTube {video_format}: '{title}'...")
    if not access_token:
        print("[*] No YouTube OAuth token provided. Simulated YouTube publish.")
        return {
            "platform": "youtube",
            "status": "simulated",
            "video_id": f"yt_sim_{os.urandom(4).hex()}",
            "title": title,
        }

    init_url = "https://www.googleapis.com/upload/youtube/v3/videos?uploadType=resumable&part=snippet,status"
    headers = {
        "Authorization": f"Bearer {access_token}",
        "Content-Type": "application/json; charset=UTF-8",
    }

    tags = ["shorts", "ai", "viral", "video"] if is_shorts else ["ai", "video", "longform"]
    final_title = f"{title[:90]} #Shorts" if is_shorts else title[:100]
    final_desc = description if description else ("#Shorts #AI" if is_shorts else "Generated by AI Content Manager")

    metadata = {
        "snippet": {
            "title": final_title,
            "description": final_desc,
            "categoryId": "22",
            "tags": tags,
        },
        "status": {
            "privacyStatus": "public",
            "selfDeclaredMadeForKids": False,
        },
    }
    init_res = requests.post(init_url, json=metadata, headers=headers, timeout=15)
    init_res.raise_for_status()
    if init_res.status_code == 200:
        upload_url = init_res.headers.get("Location")
        if upload_url and os.path.exists(video_path):
            with open(video_path, "rb") as f:
                upload_res = requests.put(upload_url, data=f, headers={"Content-Type": "video/mp4"}, timeout=120)
                upload_res.raise_for_status()
                if upload_res.status_code in [200, 201]:
                    yt_data = upload_res.json()
                    video_id = yt_data.get("id")
                    url = f"https://youtube.com/shorts/{video_id}" if is_shorts else f"https://youtube.com/watch?v={video_id}"
                    return {
                        "platform": "youtube",
                        "status": "published",
                        "video_id": video_id,
                        "url": url,
                    }

    raise RuntimeError(f"YouTube upload failed. {init_res.text}")


@_wait_for_internet_retry
def publish_to_instagram_reels(
    video_url: str,
    caption: str,
    access_token: Optional[str] = None,
    instagram_account_id: Optional[str] = None,
) -> Dict[str, Any]:
    """
    Publishes video to Instagram Reels via Instagram Graph API.
    """
    print(f"[*] Publishing to Instagram Reels...")
    if not access_token or not instagram_account_id:
        print("[*] No Instagram OAuth token provided. Simulated Instagram Reels publish.")
        return {
            "platform": "instagram",
            "status": "simulated",
            "media_id": f"ig_sim_{os.urandom(4).hex()}",
        }

    container_url = f"https://graph.facebook.com/v19.0/{instagram_account_id}/media"
    params = {
        "media_type": "REELS",
        "video_url": video_url,
        "caption": caption,
        "access_token": access_token,
    }
    res1 = requests.post(container_url, data=params, timeout=20)
    res1.raise_for_status()
    if res1.status_code != 200:
        raise RuntimeError(f"Instagram container creation failed: {res1.text}")

    container_id = res1.json().get("id")

    publish_url = f"https://graph.facebook.com/v19.0/{instagram_account_id}/media_publish"
    res2 = requests.post(publish_url, data={"creation_id": container_id, "access_token": access_token}, timeout=20)
    res2.raise_for_status()
    if res2.status_code == 200:
        return {
            "platform": "instagram",
            "status": "published",
            "media_id": res2.json().get("id"),
        }

    raise RuntimeError(f"Instagram publish failed: {res2.text}")


@_wait_for_internet_retry
def publish_to_tiktok(
    video_path: str,
    title: str,
    access_token: Optional[str] = None,
) -> Dict[str, Any]:
    """
    Publishes video to TikTok via TikTok Content Posting API v2.
    """
    print(f"[*] Publishing to TikTok: '{title}'...")
    if not access_token:
        print("[*] No TikTok OAuth token provided. Simulated TikTok publish.")
        return {
            "platform": "tiktok",
            "status": "simulated",
            "publish_id": f"tt_sim_{os.urandom(4).hex()}",
            "title": title,
        }

    if not os.path.exists(video_path):
        raise FileNotFoundError(f"Video file not found: {video_path}")

    file_size = os.path.getsize(video_path)

    # Step 1: Initialize post
    init_url = "https://open.tiktokapis.com/v2/post/publish/video/init/"
    headers = {
        "Authorization": f"Bearer {access_token}",
        "Content-Type": "application/json; charset=UTF-8",
    }
    payload = {
        "post_info": {
            "title": title[:150],
            "privacy_level": "PUBLIC_TO_EVERYONE",
            "disable_duet": False,
            "disable_stitch": False,
            "disable_comment": False,
            "video_cover_timestamp_ms": 1000,
        },
        "source_info": {
            "source": "FILE_UPLOAD",
            "video_size": file_size,
            "chunk_size": file_size,
            "total_chunk_count": 1,
        },
    }

    res_init = requests.post(init_url, json=payload, headers=headers, timeout=20)
    res_init.raise_for_status()
    init_data = res_init.json()

    publish_id = init_data.get("data", {}).get("publish_id")
    upload_url = init_data.get("data", {}).get("upload_url")

    if not upload_url:
        raise RuntimeError(f"TikTok upload initialization failed: {res_init.text}")

    # Step 2: Upload video payload
    with open(video_path, "rb") as f:
        upload_headers = {
            "Content-Range": f"bytes 0-{file_size - 1}/{file_size}",
            "Content-Type": "video/mp4",
        }
        res_upload = requests.put(upload_url, data=f, headers=upload_headers, timeout=120)
        res_upload.raise_for_status()

    return {
        "platform": "tiktok",
        "status": "published",
        "publish_id": publish_id,
        "title": title,
    }


def publish_from_social_account(
    local_mp4_path: str,
    account: Any,
    title: str,
    description: str = "",
    is_shorts: bool = True,
    public_video_url: Optional[str] = None,
) -> Dict[str, Any]:
    """
    Unified dispatcher that decrypts credentials from a SocialAccount model
    and routes the publishing payload to YouTube, TikTok, or Instagram.
    """
    platform_name = str(account.platform.value if hasattr(account.platform, "value") else account.platform).lower()
    access_token = account.get_decrypted_access_token() if hasattr(account, "get_decrypted_access_token") else getattr(account, "access_token", None)

    if platform_name == "youtube":
        return publish_to_youtube(
            video_path=local_mp4_path,
            title=title,
            description=description,
            is_shorts=is_shorts,
            access_token=access_token,
        )
    elif platform_name == "tiktok":
        return publish_to_tiktok(
            video_path=local_mp4_path,
            title=title,
            access_token=access_token,
        )
    elif platform_name == "instagram":
        target_url = public_video_url or upload_rendered_video_to_storage(local_mp4_path, job_id=str(os.urandom(4).hex()))
        return publish_to_instagram_reels(
            video_url=target_url,
            caption=f"{title}\n\n{description}",
            access_token=access_token,
            instagram_account_id=getattr(account, "platform_account_id", None) or "me",
        )
    else:
        raise ValueError(f"Unsupported social publishing platform: {platform_name}")

